async function seedRecipes() {
  try {
    const mongoUri = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/swad'
    await mongoose.connect(mongoUri)
    console.log('Connected to MongoDB')

    let seeded = 0
    let skipped = 0
    for (const r of recipes) {
      const exists = await Recipe.findOne({ name: r.name })
      if (!exists) {
        await Recipe.create({
          ...r,
          creatorRole: 'Admin',
          creatorName: 'Swad Team',
        })
        console.log(`✓ Seeded: ${r.name}`)
        seeded++
      } else {
        console.log(`– Already exists: ${r.name}`)
        skipped++
      }
    }

    console.log(`\nDone! ${seeded} seeded, ${skipped} already existed.`)
    process.exit(0)
  } catch (error) {
    console.error('Error seeding recipes:', error)
    process.exit(1)
  }
}

seedRecipes()
